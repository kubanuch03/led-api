"""
Эталонный макет карточки парковки. МЕНЯТЬ НЕЛЬЗЯ.

Макет утверждён на объекте 15.09.2026 после проверки на живой панели:

    ┌────────────────────┐
    │                    │
    │        QR          │  128 px
    │                    │
    ├────────────────────┤
    │    01KG777AAA      │   32 px: номер (жёлтый)
    │  22:45    250 сом  │        время (белый) и сумма (зелёная)
    └────────────────────┘

Меняться от карточки к карточке должно ТОЛЬКО содержимое: сам QR, номер,
время и сумма. Геометрия — высота полосы, порядок и расположение полей —
зафиксирована: на неё смотрит водитель у шлагбаума, и «улучшение» вёрстки
между двумя проездами означает, что он ищет сумму там, где её больше нет.

Эти тесты существуют, чтобы такое изменение не прошло молча: если кто-то
поменяет пропорции или порядок полей, упадёт сборка, а не восприятие
водителя на объекте.

Запуск:  python3 -m pytest tests/ -q     (нужен pytest, в образ не входит)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.render import MIN_BOX, render_card  # noqa: E402

# Ссылка боевой длины: короткий редирект, как и договаривались для панели.
SHORT_LINK = "https://pay.kg/p/A1B2C3"


def _card(**kwargs):
    defaults = dict(
        qr_data=SHORT_LINK,
        plate="01KG777AAA",
        amount="250 сом",
        time_="22:45",
    )
    defaults.update(kwargs)
    return render_card(**defaults)


def test_текст_снизу_и_полоса_ровно_20_процентов():
    """Полоса подписей — 32 px из 160. Ни больше, ни меньше."""
    _, info = _card()
    assert info["height"] == 160
    assert info["text_strip"] == 32, "высота полосы подписей изменилась — это меняет вид карточки"


def test_qr_читается_с_улицы():
    """Модуль QR не мельче 4 px, иначе код бесполезен на солнце."""
    _, info = _card()
    assert info["module_px"] >= MIN_BOX
    assert "warning" not in info


def test_на_короткой_ссылке_макет_не_перестраивается():
    """
    Штатная ссылка не должна включать адаптацию. Адаптация — аварийный
    режим для длинных ссылок, а не обычное поведение.
    """
    _, info = _card()
    assert "layout" not in info, "макет перестроился там, где этого не требуется"


def test_подписи_не_исчезают_никогда():
    """
    Даже на платёжном payload банка, где QR заведомо не читается, полоса с
    номером и суммой остаётся: водителю нужна хотя бы сумма.
    """
    _, info = _card(qr_data="https://bakai24.kg/pay?" + "x" * 118)
    assert info["text_strip"] > 0
    assert "warning" in info, "нечитаемый QR обязан сопровождаться предупреждением"


def test_кадр_ровно_по_панели():
    """160x160 — физический размер экрана у выезда."""
    png, info = _card()
    assert (info["width"], info["height"]) == (160, 160)
    assert png[:8] == b"\x89PNG\r\n\x1a\n"
